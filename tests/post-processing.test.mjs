import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { test } from 'node:test';
import { loadScripts } from './browser-scripts.mjs';

test('camera post-processing applies settings, remains ordered and toggles independently', () => {
    const context = { console, TextDecoder, TextEncoder, Uint8Array, ArrayBuffer, DataView, Blob, URL, setTimeout, clearTimeout, performance };
    context.globalThis = context; context.window = context;
    context.addEventListener = () => {}; context.removeEventListener = () => {};
    vm.createContext(context);
    vm.runInContext(fs.readFileSync(new URL('../libs/babylon.js', import.meta.url), 'utf8'), context);
    const B = context.BABYLON;
    const engine = new B.NullEngine(), scene = new B.Scene(engine);
    const camera = new B.TargetCamera('player', B.Vector3.Zero(), scene);
    scene.activeCamera = camera;
    const page = loadScripts(['js/World3D.js'], { BABYLON: B, WORLD3D_POST_ENABLED: 1, WORLD3D_POST_PIXELATE: 0, WORLD3D_POST_SATURATION: -25 });
    const view = Object.create(page.get('View3D').prototype);
    Object.assign(view, { scene, engine, camera, postCurves: new B.ColorCurves(), postPipeline: new B.DefaultRenderingPipeline('test', false, scene, [camera]), pixelPass: null });
    view.applyPostProcessing();
    assert.equal(view.postPipeline.imageProcessing.vignetteEnabled, true);
    assert.equal(view.postCurves.globalSaturation, -25);
    assert.equal(view.pixelPass, null);
    page.ctx.WORLD3D_POST_PIXELATE = 1;
    view.applyPostProcessing();
    assert.ok(view.pixelPass);
    assert.equal(camera._postProcesses.filter(p => p === view.pixelPass).length, 1);
    page.ctx.WORLD3D_POST_BLOOM = 1;
    view.applyPostProcessing();
    assert.equal(camera._postProcesses.filter(p => p === view.pixelPass).length, 1);
    assert.equal(camera._postProcesses.filter(Boolean).at(-1), view.pixelPass);
    page.ctx.WORLD3D_POST_ENABLED = 0;
    view.applyPostProcessing();
    assert.equal(view.postPipeline.imageProcessingEnabled, false);
    assert.equal(view.postPipeline.bloomEnabled, false);
    assert.equal(camera._postProcesses.filter(p => p === view.pixelPass).length, 1);
    page.ctx.WORLD3D_POST_PIXELATE = 0;
    view.applyPostProcessing();
    assert.equal(camera._postProcesses.filter(p => p === view.pixelPass).length, 0);
    view.pixelPass.dispose(); view.postPipeline.dispose(); scene.dispose(); engine.dispose();
});
